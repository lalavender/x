#!/usr/bin/env python3
"""生成/校验 compiler/project.toml 的 [link-<os>-<arch>] 自举归档闭包。

归档来自固定 LLVM 宿主记录（host.json）；C++ 运行库以文本 stub（libc++.tbd）
形式进入同一节的 `cxx` 组：它是链接输入文件而非 -l 参数，因此不需要构建机
再通过 YH_LINK_RUNTIME_FLAGS 传递。
"""

import argparse
import json
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
from llvm_cache import cache_root  # noqa: E402  闭包根的唯一定义处

COMPILER = ROOT / "compiler"
MANIFEST = COMPILER / "project.toml"
MARK_BEGIN = "# BEGIN LINK-CLOSURE (generated by tools/link-closure.py)"
MARK_END = "# END LINK-CLOSURE"

HOSTS = {
    "darwin-aarch64": ("darwin-arm64", "llvm-host-darwin-aarch64"),
    "darwin-x86_64": ("darwin-x64", "llvm-host-darwin-x86_64"),
    "linux-aarch64": ("linux-arm64", "llvm-host-linux-aarch64"),
    "linux-x86_64": ("linux-x64", "llvm-host-linux-x86_64"),
}


def host_record_path(host: str) -> Path:
    """宿主记录位置：跟随缓存根（项目外），不再写死仓库 tmp/llvm-migration。"""
    return cache_root() / HOSTS[host][1] / "host.json"


MARKER = "tmp/llvm-migration/"


def relative(path: str) -> str:
    """仓库相对归档路径 → compiler/project.toml 的路径写法。

    清单里仍写成仓库相对的 `../tmp/llvm-migration/...`：0.0.13 种子尚不支持
    `${...}` 展开，等种子滚过该特性后再改成环境变量形式。
    """
    return "../" + path


def canon_archive(text: str) -> str | None:
    """把任意布局的闭包归档路径归一成仓库内 `tmp/llvm-migration/...` 形式。

    记录可能来自：本仓库 `tmp/llvm-migration`、主 worktree 的同一路径、容器挂载点
    （`/work/tmp/llvm-migration`）或某个 workspace 的私有闭包
    （`tmp/llvm-migration-<后缀>/`）。只有归一到 canonical 前缀，才能与
    `compiler/project.toml` 里 `${YH_LLVM_ROOT}/...` 的条目比较。
    无法归一（例如系统库）时返回 None。
    """
    path = Path(text)
    if not path.is_absolute():
        path = ROOT / path
    try:
        return path.absolute().relative_to(ROOT.absolute()).as_posix()
    except ValueError:
        pass
    try:
        rel = path.relative_to(cache_root()).as_posix()
        return MARKER + rel
    except ValueError:
        pass
    marker = "tmp/llvm-migration"
    raw = path.as_posix()
    if marker not in raw:
        return None
    tail = raw.split(marker, 1)[1]
    if not tail.startswith("/"):
        slash = tail.find("/")
        if slash < 0:
            return None
        tail = tail[slash:]
    return f"{marker}/{tail.lstrip('/')}"


def archive_paths(record: dict) -> dict[str, list[str]]:
    """从宿主记录分类 bridge/lld/llvm/support 归档。"""
    bridge = canon_archive(record.get("bridge_archive", "")) or ""
    groups = {"bridge": [bridge] if bridge else [], "lld": [], "llvm": [], "support": []}
    # 归档来源两处都要看：
    #   * link_flags：clang 驱动用的 -Wl,-force_load,<归档>（旧世代记录的形态）；
    #   * selfhost_link_flags：种子自举链接用的 -force_load <归档> 对（新世代记录
    #     只保留这一份，link_flags 只剩 -isysroot/部署版本与 -lc++）。
    # 两份都归一成 canonical 归档路径，去重后分组：记录世代的差异不影响结论。
    flags: list[str] = []
    for flag in record.get("link_flags", []):
        if flag.startswith("-Wl,-force_load,"):
            flags.append(flag[len("-Wl,-force_load,"):])
    selfhost = list(record.get("selfhost_link_flags", []))
    for index, flag in enumerate(selfhost[:-1]):
        if flag == "-force_load":
            flags.append(selfhost[index + 1])
    for flag in flags:
        if not flag.endswith(".a"):
            continue
        rel = canon_archive(flag)
        if rel is None or rel == bridge:
            continue
        name = Path(rel).name
        if name.startswith("liblld"):
            groups["lld"].append(rel)
        elif name.startswith("libLLVM"):
            groups["llvm"].append(rel)
        else:
            groups["support"].append(rel)
    for key in groups:
        groups[key] = sorted(set(groups[key]))
    return groups


def render_host(host: str) -> str:
    """生成一个目标表的 TOML 文本。"""
    tag, dirname = HOSTS[host]
    record_path = host_record_path(host)
    if not record_path.is_file():
        raise SystemExit(f"缺少宿主记录 {record_path}；先运行 just llvm-host")
    record = json.loads(record_path.read_text(encoding="utf-8"))
    groups = archive_paths(record)
    if record.get("cxx_tbd"):
        groups["cxx"] = [record["cxx_tbd"]]
    # 只强制桥整库加载：桥归档里的 yh_llvm_* 是对外入口，其他 LLVM/lld 归档
    # 由符号引用按需取成员。整库 force_load 会把每个归档的全部成员都塞进产物
    # （Darwin 实测仅多 3 MB，链接命令每库多一个 -force_load），没有收益。
    whole = ["bridge"]
    out = [f"[link-{tag}]"]
    for name in ("bridge", "lld", "llvm", "support", "cxx"):
        paths = groups.get(name, [])
        out.append(f"{name} = [")
        for path in paths:
            out.append(f'  "{relative(path)}",')
        out.append("]")
    out.append(f"[link-options-{tag}]")
    out.append("whole = [" + ", ".join(f'"{name}"' for name in whole) + "]")
    return "\n".join(out) + "\n"


def render(hosts: list[str]) -> str:
    """生成所有可用目标表；缺失宿主记录跳过并提示。"""
    sections = []
    for host in hosts:
        try:
            sections.append(render_host(host))
        except SystemExit as error:
            print(f"跳过 {host}: {error}", file=sys.stderr)
    return "\n".join(sections)


def update(hosts: list[str]) -> int:
    """用生成块替换 project.toml 的标记区；标记不存在时追加。"""
    text = MANIFEST.read_text(encoding="utf-8")
    block = MARK_BEGIN + "\n" + render(hosts) + MARK_END + "\n"
    if MARK_BEGIN in text and MARK_END in text:
        start = text.index(MARK_BEGIN)
        end = text.index(MARK_END, start) + len(MARK_END)
        text = text[:start] + block + text[end:]
    else:
        text = text.rstrip() + "\n\n" + block
    MANIFEST.write_text(text, encoding="utf-8")
    print(f"更新 {MANIFEST.relative_to(ROOT)}")
    return 0


def check(host: str) -> int:
    """校验清单中的目标组与宿主记录一致。"""
    tag, rel_record = HOSTS[host]
    manifest = tomllib.loads(MANIFEST.read_text(encoding="utf-8"))
    link = manifest.get(f"link-{tag}")
    if not isinstance(link, dict):
        raise SystemExit(f"清单缺少 [link-{tag}]")
    record_path = ROOT / rel_record
    if not record_path.is_file():
        raise SystemExit(f"缺少宿主记录 {rel_record}")
    record = json.loads(record_path.read_text(encoding="utf-8"))
    expected = archive_paths(record)
    for name in ("bridge", "lld", "llvm", "support"):
        actual = {str((COMPILER / item).resolve()) for item in link.get(name, [])}
        wanted = {str((ROOT / item).resolve()) for item in expected[name]}
        if actual != wanted:
            raise SystemExit(f"[link-{tag}].{name} 与宿主记录不一致")
    whole = set(manifest.get(f"link-options-{tag}", {}).get("whole", []))
    wanted_whole = {"bridge"}
    if whole != wanted_whole:
        raise SystemExit(f"[link-options-{tag}].whole 与宿主记录不一致")
    cxx = {str((COMPILER / item).resolve()) for item in link.get("cxx", [])}
    wanted_cxx = {str((ROOT / record["cxx_tbd"]).resolve())} if record.get("cxx_tbd") else set()
    if cxx != wanted_cxx:
        raise SystemExit(f"[link-{tag}].cxx 与宿主记录不一致")
    print(f"PASS 自举闭包清单：{host}")
    return 0


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("command", choices=("generate", "update", "check"))
    parser.add_argument("--host", action="append", choices=tuple(HOSTS),
                        help="可重复；缺省为四个目标")
    args = parser.parse_args()
    hosts = args.host or list(HOSTS)
    if args.command == "generate":
        print(render(hosts), end="")
        return 0
    if args.command == "update":
        return update(hosts)
    if len(hosts) != 1:
        raise SystemExit("check 只接受一个 --host")
    return check(hosts[0])


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (OSError, ValueError, KeyError, tomllib.TOMLDecodeError) as error:
        print(f"FAIL 自举闭包清单：{error}", file=sys.stderr)
        sys.exit(1)
